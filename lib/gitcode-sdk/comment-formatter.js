class CommentFormatter {
  constructor(config) {
    this.aiSignature = '\n\n---\n🤖 generated by ai@claude';
  }

  /**
   * 对参考资料列表进行去重（根据 URL）
   * @param {Array} refs - 参考资料数组
   * @returns {Array} 去重后的参考资料数组
   */
  deduplicateRefs(refs) {
    const seen = new Set();
    return refs.filter(ref => {
      if (seen.has(ref.url)) return false;
      seen.add(ref.url);
      return true;
    });
  }

  /**
   * 根据问题类型和内容自动添加官方参考资料
   */
  addOfficialReferences(issue, body) {
    // 如果用户提供了完整的 references（包括 URL），优先使用
    if (issue.references && issue.references.length > 0) {
      body += `**官方参考资料**:\n`;
      const uniqueRefs = this.deduplicateRefs(issue.references);
      for (const ref of uniqueRefs) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
      return body;
    }

    const refs = [];

    // 1. 优先使用 Agent 推荐的类别
    if (issue.referenceCategories && Array.isArray(issue.referenceCategories)) {
      for (const category of issue.referenceCategories) {
        if (OFFICIAL_REFERENCES[category]) {
          refs.push(...OFFICIAL_REFERENCES[category]);
        }
      }
    }

    // 2. 如果没有类别推荐，使用关键词匹配作为后备
    if (refs.length === 0) {
      const content = (issue.title + issue.description + (issue.contextCode || '')).toLowerCase();

      // Python argparse / bool 相关
      if (content.includes('argparse') || content.includes('type=bool') || content.includes('add_argument')) {
        refs.push(...OFFICIAL_REFERENCES.argparse);
      }
      if (content.includes('bool') && content.includes('argparse')) {
        refs.push(...OFFICIAL_REFERENCES.bool);
      }

      // Shebang 相关
      if (content.includes('shebang') || content.includes('#!')) {
        refs.push(...OFFICIAL_REFERENCES.shebang);
      }

      // 文件 I/O 相关
      if (content.includes('file') || content.includes('path') || content.includes('os.path') || content.includes('open(')) {
        refs.push(...OFFICIAL_REFERENCES['file-io']);
      }

      // 安全相关
      if (issue.type === 'security' || content.includes('sql') || content.includes('inject') || content.includes('xss')) {
        if (content.includes('sql') && content.includes('inject')) {
          refs.push(...OFFICIAL_REFERENCES['sql-injection']);
        } else if (content.includes('xss')) {
          refs.push(...OFFICIAL_REFERENCES.xss);
        } else {
          refs.push(...OFFICIAL_REFERENCES.security);
        }
      }

      // JavaScript 异步相关
      if (content.includes('async') || content.includes('await') || content.includes('promise')) {
        refs.push(...OFFICIAL_REFERENCES.async);
      }
    }

    // 3. 添加匹配到的参考资料
    if (refs.length > 0) {
      body += `**官方参考资料**:\n`;
      const uniqueRefs = this.deduplicateRefs(refs);
      for (const ref of uniqueRefs) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
    }

    return body;
  }

  /**
   * 格式化单个问题为行内评论
   * @param {Object} issue - 问题对象
   * @param {Object} patchInfo - patch 信息（包含 position）
   */
  formatIssue(issue, patchInfo = null) {
    let body = '';

    // 严重程度图标
    const severityIcon = {
      'critical': '🚨',
      'error': '❌',
      'warning': '⚠️',
      'suggestion': '💡',
      'info': 'ℹ️'
    }[issue.severity] || '📝';

    // 标题
    body += `${severityIcon} **${issue.title}**\n\n`;

    // 描述
    if (issue.description) {
      body += `${issue.description}\n\n`;
    }

    // 上下文代码
    if (issue.contextCode) {
      body += `**上下文代码**:\n\`\`\`\n${issue.contextCode}\n\`\`\`\n\n`;
    }

    // 修复方案
    if (issue.fix) {
      body += `**修复方案**:\n`;
      if (issue.fix.code) {
        body += `\`\`\`\n${issue.fix.code}\n\`\`\`\n`;
      }
      if (issue.fix.explanation) {
        body += `${issue.fix.explanation}\n`;
      }
      body += `\n`;
    }

    // 添加官方参考资料（如果没有用户提供）
    body = this.addOfficialReferences(issue, body);

    // 用户提供的参考资料
    if (issue.references && issue.references.length > 0) {
      body += `**参考资料**:\n`;
      for (const ref of issue.references) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
    }

    // 添加 AI 签名
    body += this.aiSignature;

    // GitCode DiffNote API 的 position 字段就是新文件真实行号,直接用 issue.line
    // (issue.position 字段优先,允许调用方显式覆盖)
    let position = issue.position;
    if (position === null || position === undefined) {
      position = issue.line;
    }

    // 验证必需字段
    if (!issue.file) {
      throw new Error(`Issue missing required field: file (issue: ${issue.title})`);
    }

    // 确保返回的对象包含创建行内评论所需的所有字段
    const result = {
      path: issue.file,
      body: body,
    };

    if (position !== null && position !== undefined) {
      result.position = position;
    }

    // 添加 line（用于备用或记录）
    if (issue.line) {
      result.line = issue.line;
    }

    // 添加 commitId（如果提供）
    if (issue.commitId) {
      result.commitId = issue.commitId;
    }

    return result;
  }

  /**
   * 格式化问题列表
   * @param {Array} issues - 问题列表
   * @param {Object} patchInfos - patch 信息映射 { filename: { patch, status } }
   */
  formatIssues(issues, patchInfos = null) {
    return issues.map(issue => {
      const patchInfo = patchInfos && patchInfos[issue.file] ? patchInfos[issue.file] : null;
      return this.formatIssue(issue, patchInfo);
    });
  }

  /**
   * 格式化 "无问题" 评论
   */
  formatNoIssues() {
    return `## 代码审查\n\n未发现问题。已检查 Bug、逻辑错误和代码质量。\n\n---\n🤖 generated by ai@claude`;
  }

  /**
   * 检查是否已有 AI 签名
   */
  hasAISignature(commentBody) {
    return commentBody.includes('generated by ai@claude');
  }

  /**
   * 添加 AI 签名（如果不存在）
   */
  addAISignature(commentBody) {
    if (this.hasAISignature(commentBody)) {
      return commentBody;
    }
    return commentBody + this.aiSignature;
  }
}

module.exports = { CommentFormatter };
