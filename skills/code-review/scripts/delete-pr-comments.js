#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { GitCodeAPI } = require('../lib/gitcode-api');
const { BrowserComment } = require('../../../lib/gitcode-sdk');

function parseArgs() {
  const args = process.argv.slice(2);
  const options = {
    prNumber: null,
    commentIds: [],
    allAi: false,
    bodyIncludes: null,
    uiAuth: false,
    yes: false
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    switch (arg) {
      case '--pr':
        options.prNumber = parseInt(args[++i], 10);
        break;
      case '--comment-id':
        options.commentIds.push(args[++i]);
        break;
      case '--comment-ids':
        options.commentIds.push(...String(args[++i]).split(',').map(v => v.trim()).filter(Boolean));
        break;
      case '--all-ai':
        options.allAi = true;
        break;
      case '--body-includes':
        options.bodyIncludes = args[++i];
        break;
      case '--ui-auth':
        options.uiAuth = true;
        break;
      case '--yes':
        options.yes = true;
        break;
      default:
        throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return options;
}

function loadConfig() {
  const configPath = path.join(process.cwd(), 'config.json');
  let config = {};

  if (fs.existsSync(configPath)) {
    config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  }

  const gitcode = {
    token: process.env.GITCODE_TOKEN || config.gitcode?.token || '',
    owner: process.env.GITCODE_OWNER || config.gitcode?.owner || '',
    repo: process.env.GITCODE_REPO || config.gitcode?.repo || '',
    baseUrl: process.env.GITCODE_BASE_URL || config.gitcode?.baseUrl || 'https://api.gitcode.com'
  };

  if (!gitcode.token || !gitcode.owner || !gitcode.repo) {
    throw new Error('Missing GitCode config. Set GITCODE_TOKEN, GITCODE_OWNER, GITCODE_REPO or provide config.json.');
  }

  return { gitcode };
}

function matchesComment(comment, options) {
  if (options.commentIds.length > 0 && options.commentIds.includes(String(comment.id))) {
    return true;
  }

  if (options.allAi && comment.body && comment.body.includes('generated by ai@claude')) {
    return true;
  }

  if (options.bodyIncludes && comment.body && comment.body.includes(options.bodyIncludes)) {
    return true;
  }

  return false;
}

function printUsage() {
  console.error('Usage:');
  console.error('  node delete-pr-comments.js --pr <number> --comment-id <id> [--yes]');
  console.error('  node delete-pr-comments.js --pr <number> --comment-ids <id1,id2> [--yes]');
  console.error('  node delete-pr-comments.js --pr <number> --all-ai [--yes]');
  console.error('  node delete-pr-comments.js --pr <number> --body-includes <text> [--yes]');
  console.error('  node delete-pr-comments.js --pr <number> --comment-id <id> --ui-auth --yes');
  console.error('');
  console.error('Without --yes this script only previews matching comments.');
  console.error('Use --ui-auth when GitCode rejects public API deletion; this may open a browser for login once.');
}

async function main() {
  let options;
  try {
    options = parseArgs();
  } catch (error) {
    console.error(`Error: ${error.message}`);
    printUsage();
    process.exit(1);
  }

  if (!options.prNumber || Number.isNaN(options.prNumber)) {
    console.error('Error: --pr <number> is required');
    printUsage();
    process.exit(1);
  }

  if (options.commentIds.length === 0 && !options.allAi && !options.bodyIncludes) {
    console.error('Error: provide --comment-id, --comment-ids, --all-ai, or --body-includes');
    printUsage();
    process.exit(1);
  }

  const config = loadConfig();
  const api = new GitCodeAPI(config);
  const comments = await api.getPRComments(options.prNumber);
  const matches = comments.filter(comment => matchesComment(comment, options));

  console.log(`Matched ${matches.length} comment(s) on PR #${options.prNumber}`);
  for (const comment of matches) {
    const author = comment.user?.login || comment.user?.name || 'unknown';
    const preview = String(comment.body || '').replace(/\s+/g, ' ').slice(0, 120);
    console.log(`- ${comment.id} by ${author}: ${preview}`);
  }

  if (!options.yes) {
    console.log('\nDry run only. Re-run with --yes to delete these comments.');
    return;
  }

  let deleted = 0;
  let browserComment = null;
  for (const comment of matches) {
    try {
      await api.deletePRComment(options.prNumber, comment.id);
    } catch (error) {
      if (!options.uiAuth) {
        throw error;
      }
      console.log(`Public API delete failed for ${comment.id}: ${error.message}`);
      console.log('Trying browser-auth internal delete...');
      if (!browserComment) {
        browserComment = new BrowserComment(config);
      }
      await browserComment.deletePRComment(options.prNumber, comment);
    }
    deleted++;
    console.log(`Deleted comment ${comment.id}`);
  }

  console.log(`Deleted ${deleted}/${matches.length} comment(s).`);
}

if (require.main === module) {
  main().catch(error => {
    console.error(`Fatal error: ${error.message}`);
    process.exit(1);
  });
}

module.exports = { parseArgs, matchesComment };
