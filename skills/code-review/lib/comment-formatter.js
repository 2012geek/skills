class CommentFormatter {
  constructor(config) {
    this.language = (config && config.codeReview && config.codeReview.commentLanguage) ||
      (config && config.commentLanguage) ||
      'zh';
    this.aiSignature = '\n\n---\n🤖 generated by ai@claude';
  }

  label(key) {
    const labels = {
      zh: {
        officialReferences: '官方参考资料',
        references: '参考资料',
        contextCode: '上下文代码',
        fix: '修复方案',
        noIssuesTitle: '代码审查',
        noIssuesBody: '未发现问题。已检查 Bug、逻辑错误和代码质量。'
      },
      en: {
        officialReferences: 'Official references',
        references: 'References',
        contextCode: 'Context code',
        fix: 'Fix',
        noIssuesTitle: 'Code review',
        noIssuesBody: 'No issues found. Checked for bugs, logic errors, and code quality.'
      }
    };
    return (labels[this.language] || labels.zh)[key];
  }

  /**
   * 从 diff 中提取代码片段的行号
   * @param {Array} patchLines - diff 行数组
   * @param {number} diffIndex - diff 中的索引
   * @returns {number} 新文件中的行号
   */
  extractLineNumber(patchLines, diffIndex) {
    let newLine = 0;
    for (let i = 0; i <= diffIndex; i++) {
      if (patchLines[i].startsWith('+') || patchLines[i].startsWith(' ')) {
        newLine++;
      }
    }
    return newLine;
  }

  /**
   * 智能校正行号
   * 当行号超出文件范围时，尝试通过代码搜索找到正确的行
   * @param {Object} issue - 问题对象
   * @param {Object} patchInfo - patch 信息
   * @returns {number} 校正后的行号
   */
  correctLineNumber(issue, patchInfo) {
    if (!patchInfo || !patchInfo.patch) return issue.line;

    const { file, line, contextCode } = issue;

    // 如果没有 patch，直接返回原行号
    const patch = typeof patchInfo.patch === 'string' ? patchInfo.patch : (patchInfo.patch.diff || patchInfo.patch);
    if (!patch) return issue.line;

    const patchLines = patch.split('\n');

    // 计算文件实际行数
    let actualLines = 0;
    for (const l of patchLines) {
      if (l.startsWith('+') || l.startsWith(' ')) {
        actualLines++;
      }
    }

    // 如果行号合理（文件总行数的 120% 以内），直接返回
    if (line <= actualLines * 1.2) {
      return line;
    }

    // 行号不合理，尝试从 contextCode 中搜索
    if (contextCode) {
      const codeLines = contextCode.split('\n');
      // 取第一行非空代码作为搜索依据
      let searchSnippet = null;
      for (const codeLine of codeLines) {
        const trimmed = codeLine.trim();
        if (trimmed && !trimmed.startsWith('//') && !trimmed.startsWith('/*') && !trimmed.startsWith('*')) {
          searchSnippet = trimmed.substring(0, Math.min(30, trimmed.length));
          break;
        }
      }

      if (searchSnippet) {
        for (let i = 0; i < patchLines.length; i++) {
          const patchLine = patchLines[i].replace(/^\+/, '').trim();
          if (patchLine.includes(searchSnippet) || searchSnippet.includes(patchLine)) {
            const newLine = this.extractLineNumber(patchLines, i);
            console.warn(`⚠️  Corrected line ${line} → ${newLine} for ${file}`);
            return newLine;
          }
        }
      }
    }

    return line;
  }

  /**
   * 对参考资料列表进行去重（根据 URL）
   * @param {Array} refs - 参考资料数组
   * @returns {Array} 去重后的参考资料数组
   */
  deduplicateRefs(refs) {
    const seen = new Set();
    return refs.filter(ref => {
      if (seen.has(ref.url)) return false;
      seen.add(ref.url);
      return true;
    });
  }

  /**
   * 根据问题类型和内容自动添加官方参考资料
   */
  addOfficialReferences(issue, body) {
    // 如果用户提供了完整的 references（包括 URL），优先使用
    if (issue.references && issue.references.length > 0) {
      body += `**${this.label('officialReferences')}**:\n`;
      const uniqueRefs = this.deduplicateRefs(issue.references);
      for (const ref of uniqueRefs) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
      return body;
    }

    const refs = [];

    // 1. 优先使用 Agent 推荐的类别
    if (issue.referenceCategories && Array.isArray(issue.referenceCategories)) {
      for (const category of issue.referenceCategories) {
        if (OFFICIAL_REFERENCES[category]) {
          refs.push(...OFFICIAL_REFERENCES[category]);
        }
      }
    }

    // 2. 如果没有类别推荐，使用关键词匹配作为后备
    if (refs.length === 0) {
      const content = (issue.title + issue.description + (issue.contextCode || '')).toLowerCase();

      // Python argparse / bool 相关
      if (content.includes('argparse') || content.includes('type=bool') || content.includes('add_argument')) {
        refs.push(...OFFICIAL_REFERENCES.argparse);
      }
      if (content.includes('bool') && content.includes('argparse')) {
        refs.push(...OFFICIAL_REFERENCES.bool);
      }

      // Shebang 相关
      if (content.includes('shebang') || content.includes('#!')) {
        refs.push(...OFFICIAL_REFERENCES.shebang);
      }

      // 文件 I/O 相关
      if (content.includes('file') || content.includes('path') || content.includes('os.path') || content.includes('open(')) {
        refs.push(...OFFICIAL_REFERENCES['file-io']);
      }

      // 安全相关
      if (issue.type === 'security' || content.includes('sql') || content.includes('inject') || content.includes('xss')) {
        if (content.includes('sql') && content.includes('inject')) {
          refs.push(...OFFICIAL_REFERENCES['sql-injection']);
        } else if (content.includes('xss')) {
          refs.push(...OFFICIAL_REFERENCES.xss);
        } else {
          refs.push(...OFFICIAL_REFERENCES.security);
        }
      }

      // JavaScript 异步相关
      if (content.includes('async') || content.includes('await') || content.includes('promise')) {
        refs.push(...OFFICIAL_REFERENCES.async);
      }
    }

    // 3. 添加匹配到的参考资料
    if (refs.length > 0) {
      body += `**${this.label('officialReferences')}**:\n`;
      const uniqueRefs = this.deduplicateRefs(refs);
      for (const ref of uniqueRefs) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
    }

    return body;
  }

  /**
   * 格式化单个问题为行内评论
   * @param {Object} issue - 问题对象
   * @param {Object} patchInfo - patch 信息（包含 position）
   */
  formatIssue(issue, patchInfo = null) {
    let body = '';

    // 严重程度图标
    const severityIcon = {
      'critical': '🚨',
      'error': '❌',
      'warning': '⚠️',
      'suggestion': '💡',
      'info': 'ℹ️'
    }[issue.severity] || '📝';

    // 标题
    body += `${severityIcon} **${issue.title}**\n\n`;

    // 描述
    if (issue.description) {
      body += `${issue.description}\n\n`;
    }

    // 上下文代码
    if (issue.contextCode) {
      body += `**${this.label('contextCode')}**:\n\`\`\`\n${issue.contextCode}\n\`\`\`\n\n`;
    }

    // 修复方案
    if (issue.fix) {
      body += `**${this.label('fix')}**:\n`;
      if (issue.fix.code) {
        body += `\`\`\`\n${issue.fix.code}\n\`\`\`\n`;
      }
      if (issue.fix.explanation) {
        body += `${issue.fix.explanation}\n`;
      }
      body += `\n`;
    }

    // 添加官方参考资料（如果没有用户提供）
    body = this.addOfficialReferences(issue, body);

    // 用户提供的参考资料
    if (issue.references && issue.references.length > 0) {
      body += `**${this.label('references')}**:\n`;
      for (const ref of issue.references) {
        body += `- [${ref.title}](${ref.url})\n`;
      }
      body += `\n`;
    }

    // 添加 AI 签名
    body += this.aiSignature;

    // 🔧 方案4: 智能校正行号
    let correctedLine = issue.line;
    if (patchInfo) {
      correctedLine = this.correctLineNumber(issue, patchInfo);
    }

    // 计算 position（必须要有，否则无法创建行内评论）
    let position = issue.position;

    if (patchInfo && patchInfo.patch && !position) {
      // 如果提供了 patch 但没有 position，尝试计算
      try {
        const { GitCodeAPI } = require('./gitcode-api');
        const api = new GitCodeAPI({ gitcode: {} });
        // 🔧 使用校正后的行号计算 position
        position = api.calculatePosition(patchInfo.patch, correctedLine, patchInfo.status === 'added');
      } catch (e) {
        console.warn(`Warning: Could not calculate position for ${issue.file}:${issue.line}: ${e.message}`);
      }
    }

    // 如果 position 仍然为 null 或 undefined，使用行号作为备用方案
    // 注意：某些平台可能支持直接使用 line 而不是 position
    if (position === null || position === undefined) {
      console.warn(`Warning: No position calculated for ${issue.file}:${issue.line}, using line ${issue.line} as fallback`);
      // 对于新增文件，position 约等于行号
      // 对于修改文件，需要更精确的计算，但这里使用行号作为最后备用
      position = patchInfo && patchInfo.status === 'added' ? issue.line : null;
    }

    // 验证必需字段
    if (!issue.file) {
      throw new Error(`Issue missing required field: file (issue: ${issue.title})`);
    }

    // 确保返回的对象包含创建行内评论所需的所有字段
    const result = {
      path: issue.file,
      body: body,
    };

    // 添加 position（如果计算成功）
    if (position !== null && position !== undefined) {
      result.position = position;
    }

    // 添加 line（用于备用或记录）
    if (issue.line) {
      result.line = issue.line;
    }

    // 添加 commitId（如果提供）
    if (issue.commitId) {
      result.commitId = issue.commitId;
    }

    return result;
  }

  /**
   * 格式化问题列表
   * @param {Array} issues - 问题列表
   * @param {Object} patchInfos - patch 信息映射 { filename: { patch, status } }
   */
  formatIssues(issues, patchInfos = null) {
    return issues.map(issue => {
      const patchInfo = patchInfos && patchInfos[issue.file] ? patchInfos[issue.file] : null;
      return this.formatIssue(issue, patchInfo);
    });
  }

  /**
   * 格式化 "无问题" 评论
   */
  formatNoIssues() {
    return `## ${this.label('noIssuesTitle')}\n\n${this.label('noIssuesBody')}\n\n---\n🤖 generated by ai@claude`;
  }

  /**
   * 检查是否已有 AI 签名
   */
  hasAISignature(commentBody) {
    return commentBody.includes('generated by ai@claude');
  }

  /**
   * 添加 AI 签名（如果不存在）
   */
  addAISignature(commentBody) {
    if (this.hasAISignature(commentBody)) {
      return commentBody;
    }
    return commentBody + this.aiSignature;
  }
}

module.exports = { CommentFormatter };
