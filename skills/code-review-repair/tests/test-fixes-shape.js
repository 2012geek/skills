#!/usr/bin/env node
/**
 * Validate fixes.json shape consumed by --apply.
 * Run: node skills/code-review-repair/tests/test-fixes-shape.js
 */
const assert = require('assert');

const VALID_ACTIONS = new Set(['patch', 'deleteLines', 'revert', 'replyOnly']);

const fixesObj = {
  fixes: [
    {
      commentId: 123456,
      discussion_id: 'abc-uuid',
      filePath: 'foo.py',
      action: 'patch',
      originalCode: 'old',
      fixedCode: 'new',
      fixDescription: 'changed x to y',
      reason: 'addresses reviewer concern',
      replyBody: '感谢...\n\n---\n🤖 Generated by gitcode-code-review-repair'
    },
    {
      commentId: 789012,
      discussion_id: 'def-uuid',
      filePath: 'bar.py',
      action: 'deleteLines',
      deleteLines: [87, 90],
      fixDescription: 'removed dead code',
      replyBody: '已删除...'
    },
    {
      commentId: 345678,
      discussion_id: 'ghi-uuid',
      filePath: 'baz.py',
      action: 'revert',
      fixDescription: 'restored file',
      replyBody: '已回退...'
    },
    {
      commentId: 901234,
      discussion_id: 'jkl-uuid',
      filePath: 'qux.py',
      action: 'replyOnly',
      replyBody: '感谢意见...'
    }
  ]
};

assert(fixesObj.fixes && Array.isArray(fixesObj.fixes));
assert.strictEqual(fixesObj.fixes.length, 4);

for (const f of fixesObj.fixes) {
  assert.strictEqual(typeof f.commentId, 'number');
  assert.ok(VALID_ACTIONS.has(f.action), `invalid action: ${f.action}`);
  assert.strictEqual(typeof f.replyBody, 'string');
  assert.ok(f.replyBody.length > 0, 'replyBody must be non-empty');

  if (f.action === 'patch') {
    assert.ok(f.originalCode, 'patch requires originalCode');
    assert.ok(f.fixedCode, 'patch requires fixedCode');
  } else if (f.action === 'deleteLines') {
    assert.ok(Array.isArray(f.deleteLines), 'deleteLines requires array');
    assert.ok(f.deleteLines.length > 0, 'deleteLines requires non-empty array');
  }
  // revert + replyOnly require no extra fields
}

console.log('✓ test-fixes-shape passed');
